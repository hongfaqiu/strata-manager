// Replay against serve-tab-layout.mjs; all service and updater IO is synthetic.
async page => {
  const origin = new URL(page.url()).origin;
  const errors = [], cases = [];
  let stage = 'initial hover';
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  page.on('pageerror', error => errors.push(String(error)));
  const tooltip = page.getByRole('tooltip');
  const visibleHint = async trigger => {
    await tooltip.waitFor({ timeout: 5000 }).catch(error => { throw Error(`${stage}: ${error.message}`); });
    assert(await tooltip.textContent() === await trigger.getAttribute('data-tooltip'), 'Wrong hint text');
    assert(await trigger.getAttribute('title') === null, 'Native title remains');
    const bounds = await tooltip.boundingBox();
    const viewport = page.viewportSize();
    assert(bounds.x >= 7 && bounds.y >= 7 && bounds.x + bounds.width <= viewport.width - 7 && bounds.y + bounds.height <= viewport.height - 7, 'Hint leaves viewport');
  };
  const hide = async () => { await page.keyboard.press('Escape'); await tooltip.waitFor({ state: 'hidden' }); };
  for (const language of ['zh-CN', 'en']) for (const width of [1200, 700]) for (const theme of ['light', 'dark']) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(`${origin}/benchmark-app.html?language=${language}&tooltip-replay=${Date.now()}#benchmark`);
    const help = page.locator('.window-title-bar-button').first();
    await help.waitFor();
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme; }, theme);
    stage = `${language}-${width}-${theme} hover`;
    await page.mouse.move(0, 0);
    await help.hover();
    await visibleHint(help);
    assert((await help.getAttribute('aria-describedby'))?.includes(await tooltip.getAttribute('id')), 'Hint is not described');
    await page.screenshot({ path: `output/playwright/tab-layout/tooltip-${language}-${width}-${theme}.png` });
    await hide();
    assert(await help.getAttribute('aria-describedby') === null, 'Description was not cleaned up');
    const disabled = help;
    await disabled.evaluate(element => { element.disabled = true; });
    assert(await disabled.isDisabled(), 'Expected disabled image action');
    await page.mouse.move(0, 0);
    await disabled.hover();
    await visibleHint(disabled);
    await hide();
    await disabled.evaluate(element => { element.disabled = false; });
    cases.push(`${language}-${width}-${theme}: hover, disabled, description, viewport`);
  }
  await page.setViewportSize({ width: 900, height: 900 });
  await page.goto(`${origin}/benchmark-app.html?language=zh-CN&tooltip-replay=${Date.now()}#benchmark`);
  const help = page.locator('.window-title-bar-button').first();
  const guide = page.getByRole('button', { name: '测试说明', exact: true });
  await help.waitFor();
  await page.mouse.move(0, 0);
  await page.keyboard.press('Tab');
  await help.hover();
  await help.focus();
  stage = 'keyboard during hover delay';
  await visibleHint(help);
  await hide();
  await help.evaluate(element => element.blur());
  stage = 'rapid re-entry';
  await page.mouse.move(0, 0);
  await help.hover();
  await page.mouse.move(0, 0);
  await help.hover();
  await visibleHint(help);
  await tooltip.hover();
  stage = 'hoverable hint';
  await page.waitForTimeout(180);
  assert(await tooltip.isVisible(), 'Hovering hint dismisses it');
  await page.mouse.move(0, 0);
  await tooltip.waitFor({ state: 'hidden' });
  cases.push('keyboard during hover delay; rapid re-entry; hoverable hint');

  await page.getByRole('radiogroup', { name: 'Benchmark 类型', exact: true }).getByRole('radio', { name: '场景测试', exact: true }).click();
  await guide.click();
  const dialog = page.getByRole('dialog');
  await dialog.waitFor();
  const close = dialog.getByRole('button', { name: '关闭', exact: true });
  stage = 'dialog close hover';
  await close.hover();
  await visibleHint(close);
  assert(await tooltip.evaluate(element => !!element.closest('[role="dialog"]')), 'Hint outside dialog Portal');
  await hide();
  assert(await dialog.isVisible(), 'Hint Escape closed dialog');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  await guide.click();
  await dialog.waitFor();
  await close.evaluate(element => element.blur());
  await page.mouse.move(0, 0);
  await tooltip.waitFor({ state: 'hidden' });
  await close.hover();
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden', timeout: 5000 });
  cases.push('dialog Portal; visible-hint Escape; pending-hint Escape');

  await page.evaluate(() => {
    const fixture = document.createElement('div');
    fixture.id = 'tooltip-edge-fixture';
    fixture.style.cssText = 'position:fixed;right:0;bottom:0;z-index:1100;background:white';
    fixture.innerHTML = '<span id="original-description">Existing description</span><button id="edge-hint" aria-describedby="original-description">Edge</button><label for="hint-input" data-tooltip="Associated input hint">Label</label><input id="hint-input"><label data-tooltip="Nested input hint"><input id="nested-hint-input"></label>';
    fixture.querySelector('button').dataset.tooltip = 'Long path: C:\\models\\' + 'long-directory-name\\'.repeat(25);
    document.body.append(fixture);
  });
  const edge = page.locator('#edge-hint');
  stage = 'long edge hint';
  await edge.hover();
  await visibleHint(edge);
  assert((await edge.getAttribute('aria-describedby')).includes('original-description'), 'Existing description was lost');
  await hide();
  assert(await edge.getAttribute('aria-describedby') === 'original-description', 'Existing description was not restored');
  await page.mouse.move(0, 0);
  await page.keyboard.press('Tab');
  for (const [id, text] of [['hint-input', 'Associated input hint'], ['nested-hint-input', 'Nested input hint']]) {
    await page.locator(`#${id}`).focus();
    await tooltip.waitFor({ timeout: 5000 }).catch(error => { throw Error(`${id}: ${error.message}`); });
    assert(await tooltip.textContent() === text, `Missing label hint: ${id}`);
    assert((await page.locator(`#${id}`).getAttribute('aria-describedby'))?.includes(await tooltip.getAttribute('id')), 'Input is not described');
    await page.locator(`label${id === 'hint-input' ? '[for="hint-input"]' : ':has(#nested-hint-input)'}`).hover();
    assert((await page.locator(`#${id}`).getAttribute('aria-describedby'))?.includes(await tooltip.getAttribute('id')), 'Label hover detached the focused input description');
    await hide();
  }
  await page.locator('#nested-hint-input').evaluate(element => element.blur());
  await page.mouse.move(0, 0);
  await tooltip.waitFor({ state: 'hidden' });
  await edge.dispatchEvent('pointerover', { pointerType: 'touch' });
  await page.waitForTimeout(450);
  assert(!await tooltip.isVisible(), 'Touch opened hover hint');
  await edge.hover();
  await tooltip.waitFor({ timeout: 5000 }).catch(error => { throw Error(`edge after focus: ${error.message}`); });
  await edge.evaluate(element => { element.dataset.tooltip = 'Updated hint'; });
  await page.waitForFunction(() => document.querySelector('[role="tooltip"]')?.textContent === 'Updated hint');
  await edge.evaluate(element => element.remove());
  await tooltip.waitFor({ state: 'hidden' });
  await page.locator('#tooltip-edge-fixture').evaluate(element => element.remove());
  cases.push('long edge path; existing description; associated and nested label; touch; live text; removed trigger');

  await page.goto(`${origin}/benchmark-app.html?language=zh-CN&tooltip-replay=${Date.now()}#chat`);
  const sampling = page.locator('#sampling-btn');
  await sampling.waitFor();
  await sampling.click();
  await dialog.waitFor();
  if (await dialog.getByRole('combobox').first().getAttribute('aria-expanded') === 'true') await page.keyboard.press('Escape');
  const thinking = page.getByRole('radiogroup');
  await thinking.waitFor();
  const layout = await thinking.evaluate(element => ({ display: getComputedStyle(element).display, width: element.getBoundingClientRect().width, total: [...element.children].reduce((sum, child) => sum + child.getBoundingClientRect().width, 0) + 22 }));
  assert(layout.display === 'flex' && layout.width <= layout.total + 2, 'Chat thinking rail stretches');
  await thinking.getByRole('radio').first().focus();
  await page.keyboard.press('End');
  assert(await thinking.getByRole('radio').last().getAttribute('aria-checked') === 'true', 'Chat thinking keyboard failed');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  cases.push('chat thinking drawer content width and keyboard');
  assert(!errors.length, `Browser errors: ${errors.join('; ')}`);
  return { passed: true, cases, browserErrors: errors };
}
